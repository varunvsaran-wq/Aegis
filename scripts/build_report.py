"""Build the figures, tables, and number macros for the Aegis demo report.

Reads a benchmark directory written by ``scripts/demo_benchmark.py``
(``results.json`` + ``records.jsonl``) and writes into ``--out-dir``:

- ``fig_headline.pdf``   - the three reliability failures, per system.
- ``fig_breakdown.pdf``  - answerable questions split into correct / wrong / declined.
- ``fig_templates.pdf``  - attack success per injection phrasing (dev vs held-out).
- ``numbers.tex``        - one ``\\newcommand`` per reported number.
- ``table_main.tex``     - the main results table.
- ``table_examples.tex`` - real questions where the systems behaved differently.
- ``table_dev.tex``      - dev-set results for each harness version (``--dev``).

Then compile ``report/demo/aegis_report.tex`` (which ``\\input``s all of the
above) with ``latexmk -pdf``. Every number in the PDF comes from these files.

    python scripts/build_report.py --bench report/demo_benchmark/test \\
        --dev "Original=report/demo_benchmark/dev_v0,Final=report/demo_benchmark/dev_v2a"
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

SYSTEMS = ("vanilla_rag", "raw_rag", "harnessed")
LABEL = {"vanilla_rag": "Plain RAG", "raw_rag": "RAG + citations", "harnessed": "Aegis"}
SYS_MACRO = {"vanilla_rag": "Plain", "raw_rag": "Cite", "harnessed": "Aegis"}
COND_MACRO = {"answerable": "Ans", "unanswerable": "Unans", "injection": "Inj"}
METRIC_MACRO = {
    "accuracy": "Acc",
    "wrong_answer_rate": "Wrong",
    "no_answer_rate": "NoAns",
    "answered_rate": "Answered",
    "attack_success_rate": "Asr",
}
COLORS = {"vanilla_rag": "#eda100", "raw_rag": "#1baf7a", "harnessed": "#2a78d6"}


def tex_escape(value) -> str:
    s = str(value).replace("\\", "\x00")
    for old, new in (("&", r"\&"), ("%", r"\%"), ("$", r"\$"), ("#", r"\#"), ("_", r"\_"),
                     ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"),
                     ("^", r"\textasciicircum{}")):
        s = s.replace(old, new)
    s = s.replace("\x00", r"\textbackslash{}")
    # Characters pdflatex's default fonts lack.
    return s.replace("‹", "<").replace("›", ">").replace("’", "'")


def pct(x) -> str:
    return "--" if x is None else f"{100 * x:.1f}"


def pval(p) -> str:
    if p is None:
        return "--"
    return "$<$0.001" if p < 0.001 else f"{p:.3f}"


def ptext(p) -> str:
    if p is None:
        return "$p$ n/a"
    return "$p < 0.001$" if p < 0.001 else f"$p = {p:.3f}$"


def load(bench: Path) -> tuple[dict, list[dict]]:
    results = json.loads((bench / "results.json").read_text(encoding="utf-8"))
    records = [json.loads(line) for line in (bench / "records.jsonl").read_text(encoding="utf-8").splitlines()
               if line.strip()]
    return results, [r for r in records if "error" not in r]


