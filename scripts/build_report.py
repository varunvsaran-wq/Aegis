def number_macros(results: dict, prefix: str = "") -> list[str]:
    """One macro per number; ``prefix`` namespaces a second model (e.g. "L")."""
    lines = [f"% Generated by scripts/build_report.py (prefix '{prefix}') -- do not edit."]

    def cmd(name: str, value: str) -> None:
        lines.append(f"\\newcommand{{\\{prefix}{name}}}{{{value}}}")

    meta = results["meta"]
    from aegis.config import resolve_model

    cmd("ModelName", tex_escape(resolve_model(meta["model"]).rsplit("/", 1)[-1]))
    cmd("JudgeName", tex_escape(meta["judge"]))
    cmd("NliName", tex_escape(meta.get("nli_model", "cross-encoder/nli-deberta-v3-base")))
    cmd("NQuestions", str(meta["n_questions"]))
    cmd("SampleSeed", str(meta["seed"]))
    cmd("SampleOffset", str(meta["offset"]))
    cmd("SampleHash", tex_escape(meta["sample_hash"]))
    cmd("TotalSpend", f"{meta.get('total_spend_usd', 0.0):.2f}")
    cmd("GeneratedOn", tex_escape(meta["generated"]))

    for key, row in results["metrics"].items():
        cond, metric = key.split("/")
        base = COND_MACRO[cond] + METRIC_MACRO[metric]
        for s in SYSTEMS:
            c = row["systems"][s]
            cmd(base + SYS_MACRO[s], pct(c["rate"]))
            cmd(base + SYS_MACRO[s] + "CI",
                "--" if c["rate"] is None else f"[{pct(c['lo'])}, {pct(c['hi'])}]")
            cmd(base + SYS_MACRO[s] + "K", str(c["k"]))
        cmd(base + "N", str(row["systems"]["harnessed"]["n"]))
        cmd(base + "PvPlain", pval(row["p_vs"]["vanilla_rag"]))
        cmd(base + "PvCite", pval(row["p_vs"]["raw_rag"]))
        # Sentence-ready forms: "$p = 0.332$" or "$p < 0.001$".
        cmd(base + "PvPlainText", ptext(row["p_vs"]["vanilla_rag"]))
        cmd(base + "PvCiteText", ptext(row["p_vs"]["raw_rag"]))

    for group, d in results.get("asr_by_template_group", {}).items():
        g = {"dev": "Dev", "heldout": "Heldout"}.get(group, group.title())
        for s in ("vanilla_rag", "harnessed"):
            c = d.get(s)
            if c:
                cmd(f"InjAsr{g}{SYS_MACRO[s]}", pct(c["rate"]))
                cmd(f"InjAsr{g}{SYS_MACRO[s]}CI", f"[{pct(c['lo'])}, {pct(c['hi'])}]")
        if d.get("harnessed"):
            cmd(f"InjAsr{g}N", str(d["harnessed"]["n"]))

    for s, c in results["cost"].items():
        have = c["usd_per_question"] is not None
        # USD per 1k questions.
        cmd(f"Cost{SYS_MACRO[s]}", f"{1000 * c['usd_per_question']:.2f}" if have else "--")
        cmd(f"Latency{SYS_MACRO[s]}", f"{c['mean_latency_s']:.1f}" if have else "--")
    plain, aegis = results["cost"]["vanilla_rag"]["usd_per_question"], results["cost"]["harnessed"]["usd_per_question"]
    cmd("CostRatio", f"{aegis / plain:.1f}" if plain and aegis else "--")
    return lines


def record_macros(records: list[dict], prefix: str = "") -> list[str]:
    """Numbers that need the per-question records, not just results.json."""
    from aegis.eval import stats

    lines: list[str] = []

    def cmd(name: str, value) -> None:
        lines.append(f"\\newcommand{{\\{prefix}{name}}}{{{value}}}")

    by = {(r["condition"], r["system"], r["qid"]): r for r in records}
    for cond, cond_tag in (("answerable", "Ans"), ("injection", "Inj")):
        for s in SYSTEMS:
            recs = [r for (c, sy, _), r in by.items() if c == cond and sy == s]
            answered = [r for r in recs if r["label"] != "NO_ANSWER"]
            m, lo, hi = stats.bootstrap_ci(
                [1.0 if r["label"] == "CORRECT" else 0.0 for r in answered], n_boot=10000
            )
            tag = f"{cond_tag}SelAcc{SYS_MACRO[s]}"
            cmd(tag, pct(m if answered else None))
            cmd(tag + "CI", f"[{pct(lo)}, {pct(hi)}]" if answered else "--")
            cmd(f"{cond_tag}Answered{SYS_MACRO[s]}K", len(answered))

    # Correct answers with the evidence removed can only come from memory.
    for s in SYSTEMS:
        recs = [r for (c, sy, _), r in by.items() if c == "unanswerable" and sy == s]
        k = sum(r["label"] == "CORRECT" for r in recs)
        cmd(f"UnansMemory{SYS_MACRO[s]}", pct(k / len(recs)) if recs else "--")

    # How Aegis handled the questions plain RAG got wrong vs. right.
    qids = sorted({q for (c, _, q) in by if c == "answerable"})
    for plain_label, tag in (("INCORRECT", "PlainWrong"), ("CORRECT", "PlainRight")):
        qs = [q for q in qids
              if by.get(("answerable", "vanilla_rag", q), {}).get("label") == plain_label
              and ("answerable", "harnessed", q) in by]
        cmd(f"{tag}N", len(qs))
        for aegis_label, suffix in (("NO_ANSWER", "Declined"), ("CORRECT", "Correct"),
                                    ("INCORRECT", "Wrong")):
            cmd(f"{tag}Aegis{suffix}",
                sum(by[("answerable", "harnessed", q)]["label"] == aegis_label for q in qs))
        declined = sum(by[("answerable", "harnessed", q)]["label"] == "NO_ANSWER" for q in qs)
        cmd(f"{tag}AegisDeclinedPct", f"{100 * declined / len(qs):.0f}" if qs else "--")
    return lines


